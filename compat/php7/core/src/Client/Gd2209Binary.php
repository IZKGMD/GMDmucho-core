<?php

declare (strict_types=1);
namespace MuchoCore\Client;

use RuntimeException;
/**
 * Exact-build Windows GD 2.209 URL patcher.
 *
 * No code/instruction patching, no binary version spoofing, no PE resizing.
 * Patched URL bytes cannot exceed their original length. For long HTTPS\n * subdomains, MuchoCore's /a/ route alias is used when needed.
 */
final class Gd2209Binary
{
    // Exact unmodified Windows GD 2.209 builds, verified against supplied PE64 binaries.
    // Never accept arbitrary EXEs solely because they contain Boomlings URLs.
    const SHA256 = '524265b3781596fcc7c9e4d60dc5ac2d0a4cd9530ee3ea637e123f9ac1f9b6a8';
    const SHA256_OCT19 = '4eee06d5c2e2213b4ba2b1f6233dd426bbdd0e9b29d7c375e499516b6f8f69d5';
    const BUILDS = [self::SHA256 => ['label' => 'Geometry Dash 2.209 (13 Oct 2026)', 'size' => 13158400, 'url_count' => 111], self::SHA256_OCT19 => ['label' => 'Geometry Dash 2.209 (19 Oct 2026)', 'size' => 13178880, 'url_count' => 113]];
    /** @return array{label:string,size:int,url_count:int,sha256:string}|null */
    public static function identifyBuild(string $path)
    {
        if (!is_file($path) || !is_readable($path)) {
            return null;
        }
        $size = filesize($path);
        if ($size !== 13158400 && $size !== 13178880) {
            return null;
        }
        $hash = hash_file('sha256', $path);
        if ($hash === false || !isset(self::BUILDS[$hash])) {
            return null;
        }
        return ['sha256' => $hash] + self::BUILDS[$hash];
    }
    public static function supports(string $path): bool
    {
        return self::identifyBuild($path) !== null;
    }
    /**
     * Refuse to pass an unknown modern 2.209 build through the legacy
     * short-URL patcher: that strategy can produce a misleading usable EXE.
     */
    public static function resembles2209(string $path): bool
    {
        $size = @filesize($path);
        if (!is_file($path) || $size === false || $size < 10 * 1024 * 1024 || $size > 20 * 1024 * 1024) {
            return false;
        }
        $bytes = @file_get_contents($path);
        return is_string($bytes) && str_contains($bytes, 'getGJNotifications.php') && str_contains($bytes, 'getGJThreadInvites.php');
    }
    /**
     * Generate a byte-exact, non-mutating preflight report.
     *
     * Uses the SAME exact-build validation and patch implementation as the
     * admin patcher. Does not upload, execute or write the executable.
     *
     * @return array<string, mixed>
     */
    public static function inspectFile(string $inputPath, string $serverUrl): array
    {
        list(, $report) = self::prepareFile($inputPath, $serverUrl);
        return $report;
    }
    /**
     * Emit narrowly scoped Apache routes from the exact patched client URLs.
     *
     * This is a SNIPPET for the domain document root, not an automatic edit.
     * Paths are enumerated from a verified patch plan; no catch-all rewrites.
     */
    public static function apacheRewriteSnippet(array $report, string $handler = 'mc/public/php7.php'): string
    {
        if (!preg_match('~^[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*/[A-Za-z0-9_-]+\.php$~D', $handler)) {
            throw new RuntimeException('Invalid PHP route handler.');
        }
        $routes = $report['routes'] ?? null;
        if (!is_array($routes) || $routes === []) {
            throw new RuntimeException('A verified route manifest is required.');
        }
        $unique = [];
        foreach ($routes as $route) {
            $path = ltrim((string) ($route['target_path'] ?? ''), '/');
            if (!preg_match('~^[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*\.php$~D', $path) && !preg_match('~^[A-Za-z0-9_-]+\.php$~D', $path)) {
                throw new RuntimeException('Unexpected patched GD API route.');
            }
            $unique[$path] = true;
        }
        $paths = array_keys($unique);
        sort($paths, SORT_STRING);
        $lines = ['# Generated by MuchoCore GD 2.209 Patch Studio.', '# Add to the DOMAIN ROOT .htaccess before catch-all RewriteRule lines.', '# Server: ' . (string) ($report['server_url'] ?? '(unknown)'), '# Routes: ' . count($paths), 'RewriteEngine On'];
        foreach (array_chunk($paths, 10) as $chunk) {
            $escaped = array_map(static function (string $path): string {
                return preg_quote($path, '~');
            }, $chunk);
            $lines[] = 'RewriteRule ^(?:' . implode('|', $escaped) . ')$ ' . $handler . ' [QSA,L,NC]';
        }
        return implode("\n", $lines) . "\n";
    }
    /**
     * @return array<string, mixed> Matches WindowsClientPatcher::patchFile() manifest.
     */
    public static function patchFile(string $inputPath, string $outputPath, string $serverUrl): array
    {
        if ($inputPath === $outputPath || realpath($inputPath) !== false && realpath($inputPath) === realpath($outputPath)) {
            throw new RuntimeException('Never overwrite the original Geometry Dash executable.');
        }
        if (file_exists($outputPath) || is_link($outputPath)) {
            throw new RuntimeException('Output client already exists. Choose a new filename.');
        }
        list($data, $report) = self::prepareFile($inputPath, $serverUrl);
        $directory = dirname($outputPath);
        if (!is_dir($directory) || !is_writable($directory)) {
            throw new RuntimeException('Output folder is not writable.');
        }
        // Write adjacent to the destination so a completed client appears at
        // once, not as a half-written executable. A failed write is removed.
        $temporary = @tempnam($directory, '.muchocore-patch-');
        if ($temporary === false) {
            throw new RuntimeException('Cannot create temporary client output.');
        }
        try {
            $written = @file_put_contents($temporary, $data, LOCK_EX);
            if ($written !== strlen($data) || hash_file('sha256', $temporary) !== $report['output_sha256']) {
                throw new RuntimeException('Patched client integrity verification failed.');
            }
            @chmod($temporary, 0640);
            if (file_exists($outputPath) || is_link($outputPath) || !@rename($temporary, $outputPath)) {
                throw new RuntimeException('Cannot publish patched client without overwriting another file.');
            }
        } finally {
            if (is_file($temporary)) {
                @unlink($temporary);
            }
        }
        return $report;
    }
    /**
     * @return array{string,array<string,mixed>}
     */
    private static function prepareFile(string $inputPath, string $serverUrl): array
    {
        $server = WindowsClientPatcher::validateServerUrl($serverUrl);
        $parts = parse_url($server);
        if (($parts['scheme'] ?? '') !== 'https' || isset($parts['port'])) {
            throw new RuntimeException('GD 2.209 requires an HTTPS origin without a port.');
        }
        $build = self::identifyBuild($inputPath);
        if ($build === null) {
            throw new RuntimeException('Unsupported GD 2.209 EXE. Use an original known build (SHA-256 must match).');
        }
        $binary = @file_get_contents($inputPath);
        if ($binary === false) {
            throw new RuntimeException('Unable to read the original client.');
        }
        list($data, $count, $paths, $routes) = self::patchBytes($binary, (string) $parts['host']);
        if ($count !== $build['url_count']) {
            throw new RuntimeException('GD 2.209 endpoint count mismatch: expected ' . $build['url_count'] . ', found ' . $count . '. No output was written.');
        }
        $modes = ['database' => 0, 'short_alias' => 0, 'root_alias' => 0];
        foreach ($routes as $route) {
            ++$modes[$route['mode']];
        }
        return [$data, ['server_url' => $server, 'input_size' => strlen($binary), 'output_size' => strlen($data), 'replacements' => ['GD 2.209 server URLs' => $count], 'replacement_count' => $count, 'input_sha256' => $build['sha256'], 'source_build' => $build['label'], 'output_sha256' => hash('sha256', $data), 'endpoint_paths' => $paths, 'routes' => $routes, 'route_modes' => $modes, 'requires_short_alias' => $modes['short_alias'] > 0, 'requires_root_alias' => $modes['root_alias'] > 0, 'patch_engine' => 'gd2209-exact-rdata-v2', 'verified' => 'static-binary-only']];
    }
    /**
     * Portable core for regression testing with a synthetic PE64 fixture.
     * Input must contain an x64 PE with a .rdata section.
     *
     * @return array{string, int, list<string>, list<array{source_path:string,target_path:string,mode:string}>}
     */
    public static function patchBytes(string $input, string $targetHost): array
    {
        if (!preg_match('/^[A-Za-z0-9.-]+$/D', $targetHost)) {
            throw new RuntimeException('Invalid target hostname.');
        }
        if (substr($input, 0, 2) !== 'MZ' || strlen($input) < 0x100) {
            throw new RuntimeException('Not a PE executable.');
        }
        $length = strlen($input);
        $peOffset = unpack('V', substr($input, 0x3c, 4))[1];
        if ($peOffset < 0x40 || $peOffset > $length - 24 || substr($input, $peOffset, 4) !== "PE\x00\x00") {
            throw new RuntimeException('Invalid PE header offset or signature.');
        }
        if (unpack('v', substr($input, $peOffset + 4, 2))[1] !== 0x8664) {
            throw new RuntimeException('Expected Windows x64 executable.');
        }
        $sections = unpack('v', substr($input, $peOffset + 6, 2))[1];
        $optionalSize = unpack('v', substr($input, $peOffset + 20, 2))[1];
        $sectionOffset = $peOffset + 24 + $optionalSize;
        if ($sections < 1 || $sections > 96 || $sectionOffset > $length || $sections > intdiv($length - $sectionOffset, 40)) {
            throw new RuntimeException('Invalid PE section table.');
        }
        $rdataOffset = -1;
        $rdataSize = 0;
        for ($i = 0; $i < $sections; $i++) {
            $offset = $sectionOffset + $i * 40;
            if (substr($input, $offset, 8) !== ".rdata\x00\x00") {
                continue;
            }
            $rdataSize = unpack('V', substr($input, $offset + 16, 4))[1];
            $rdataOffset = unpack('V', substr($input, $offset + 20, 4))[1];
            break;
        }
        if ($rdataOffset < 0 || $rdataSize < 100 || $rdataOffset + $rdataSize > strlen($input)) {
            throw new RuntimeException('Invalid or missing PE .rdata section.');
        }
        $section = substr($input, $rdataOffset, $rdataSize);
        $regex = '~https?://(?:www\.boomlings\.com|boomlings\.com|www\.geometrydash\.com)/(?:database|databas)/[A-Za-z0-9._/-]+\.php(?=\x00)~';
        $matches = [];
        preg_match_all($regex, $section, $matches, PREG_OFFSET_CAPTURE);
        $count = 0;
        $paths = [];
        $routes = [];
        foreach ($matches[0] as list($url, $position)) {
            if ($position > 0 && !in_array($section[$position - 1], ["\x00", "\n", "\r", ' ', '"', "'"], true)) {
                continue;
            }
            $oldPath = substr($url, strpos($url, '/', strpos($url, '://') + 3));
            if (str_starts_with($oldPath, '/databas/')) {
                $oldPath = '/database/' . substr($oldPath, strlen('/databas/'));
            }
            $patched = 'https://' . $targetHost . $oldPath;
            $mode = 'database';
            $oldLength = strlen($url);
            if (strlen($patched) > $oldLength && str_starts_with($oldPath, '/database/')) {
                // GD 2.209 reserves only its original URL bytes. The /a/
                // shared-hosting alias saves enough space for long subdomains.
                $patched = 'https://' . $targetHost . '/a/' . substr($oldPath, strlen('/database/'));
                $mode = 'short_alias';
            }
            if (strlen($patched) > $oldLength && str_starts_with($oldPath, '/database/')) {
                // The root GD API alias also works through public/index.php
                // and the PHP7 native router, saving nine path bytes.
                $patched = 'https://' . $targetHost . '/' . substr($oldPath, strlen('/database/'));
                $mode = 'root_alias';
            }
            if (strlen($patched) > $oldLength) {
                throw new RuntimeException("GD 2.209 hostname too long for in-place patch; use a shorter HTTPS domain or alias.");
            }
            $section = substr_replace($section, $patched . str_repeat("\x00", $oldLength - strlen($patched)), $position, $oldLength);
            $count++;
            $paths[] = $oldPath;
            $routes[] = ['source_path' => $oldPath, 'target_path' => substr($patched, strlen('https://' . $targetHost)), 'mode' => $mode];
        }
        if ($count === 0) {
            throw new RuntimeException('No supported GD server endpoints found in PE .rdata.');
        }
        // The original bytes outside .rdata are left untouched.
        $patchedBinary = substr_replace($input, $section, $rdataOffset, $rdataSize);
        if (strlen($patchedBinary) !== strlen($input)) {
            throw new RuntimeException('PE image size mismatch after patch.');
        }
        return [$patchedBinary, $count, array_values(array_unique($paths)), $routes];
    }
}
